-- Contabilità Primafila Service: avvio 2027
create table if not exists public.contabilita_eventi (
 id bigint generated by default as identity primary key,
 cliente_id bigint not null references public.clienti(id) on delete restrict,
 preventivo_id bigint null references public.preventivi(id) on delete set null,
 nome_evento text not null, data_evento date,
 imponibile numeric(12,2) not null default 0, iva_percentuale numeric(5,2) not null default 22,
 iva numeric(12,2) not null default 0, totale numeric(12,2) not null default 0, note text,
 fattura_emessa boolean not null default false, numero_fattura text, data_fattura date,
 created_at timestamptz not null default now()
);
create table if not exists public.contabilita_pagamenti (
 id bigint generated by default as identity primary key,
 evento_contabile_id bigint not null references public.contabilita_eventi(id) on delete cascade,
 data_pagamento date not null default current_date, importo numeric(12,2) not null check (importo > 0),
 metodo text, note text, created_at timestamptz not null default now()
);
create index if not exists contabilita_eventi_data_idx on public.contabilita_eventi(data_evento);
create index if not exists contabilita_eventi_cliente_idx on public.contabilita_eventi(cliente_id);
create index if not exists contabilita_pagamenti_evento_idx on public.contabilita_pagamenti(evento_contabile_id);
alter table public.contabilita_eventi enable row level security;
alter table public.contabilita_pagamenti enable row level security;
drop policy if exists "contabilita_eventi_autenticati" on public.contabilita_eventi;
drop policy if exists "contabilita_pagamenti_autenticati" on public.contabilita_pagamenti;
create policy "contabilita_eventi_autenticati" on public.contabilita_eventi for all to authenticated using (true) with check (true);
create policy "contabilita_pagamenti_autenticati" on public.contabilita_pagamenti for all to authenticated using (true) with check (true);
